public class Cama {
    private int piso;
    private int numero;
    private String estado;

    public Cama(int piso, int numero, String estado) {
        this.piso = piso;
        this.numero = numero;
        this.estado = estado;
    }

    public int getPiso() {
        return piso;
    }

    public void setPiso(int piso) {
        this.piso = piso;
    }

    public int getNumero() {
        return numero;
    }

    public void setNumero(int numero) {
        this.numero = numero;
    }

    public String getEstado() {
        return estado;
    }

    public void setEstado(String estado) {
        this.estado = estado;
    }

    
}


